#!/bin/sh
# bench/ab/mkrename.sh -- **auto-generate** the symbol rename table from a given flashvec.h
#
# usage: mkrename.sh <header> <prefix> <out>
#
# Why generate instead of hand-write: the registry (ab_ops.h) only says which ops to
# measure; symbol isolation is a property of the header. Every name of the form "fv_xxx("
# in the header (= a function name, including static inline internals) is renamed to
# <prefix>xxx, so ab_variant.cpp can write fv_vec2_add_x4(...) directly and it lands in
# this side's namespace -- **a new entry point is isolated the moment it lands, with no
# rename table to maintain**.
#
# Only names followed by an opening paren are collected: types (fv_vec2) and constants
# (FV_EPS) are never touched.
set -u
hdr=$1
pfx=$2
out=$3

{
    printf '/* generated by mkrename.sh %s %s; do not edit by hand */\n' "$pfx" "$hdr"
    printf '#ifndef AB_RENAME_GENERATED_H\n#define AB_RENAME_GENERATED_H\n'
    grep -ohE '\bfv_[A-Za-z0-9_]+[[:space:]]*\(' "$hdr" |
        sed -E 's/[[:space:]]*\($//' |
        sort -u |
        while IFS= read -r n; do
            [ -n "$n" ] || continue
            printf '#define %s %s%s\n' "$n" "$pfx" "${n#fv_}"
        done
    printf '#endif\n'
} > "$out.tmp" && mv "$out.tmp" "$out"
