/* bench/ab/ab_variant.cpp -- the variant TU template: one source file compiled twice (A/B)
 *
 * Each variant TU includes one version of include/flashvec.h (and src/flashvec_batch.cpp
 * when needed) and exports **the whole timing loop** (ab_X_loop). Hence:
 *   library form -> the loop holds a cross-function call (= what a static-library consumer
 *                   gets)
 *   inline form  -> the loop is inlined (= what the refactor wants)
 * The driver (ab_bench.cpp) only knows the three symbols ab_X_loop / ab_X_abi /
 * ab_X_opflags; it has no idea what the batch entry points are called or how many exist.
 *
 * This file **spells out the library names directly** (fv_vec2_add_x4 and friends): the
 * Makefile forces in an autogenerated rename table with -include (mkrename.sh collects every
 * fv_xxx( name from this side's header), so the same source lands in ab_a_* on side A and in
 * ab_b_* on side B -- no neutral aliases and no hand-maintained rename table.
 *
 * Compile flags (all passed by the Makefile):
 *   -include <build>/rename_a.h|<build>/rename_b.h   <- must precede the header (macro rename)
 *   -DAB_HDR='"path/flashvec.h"'                     <- this variant's header
 *   -DAB_WITH_SRC=1 -DAB_SRC='"path/flashvec_batch.cpp"'  <- library form only
 *   -DAB_HAVE_STREAM=0|1                   <- does this side's header have _stream (auto)
 *   -DAB_LOOP_NAME=ab_a_loop -DAB_ABI_NAME=ab_a_abi -DAB_FLAGS_NAME=ab_a_opflags
 *
 * Adding an op: one line in the ab_ops.h registry + one abt_<ID> thunk below. That is all. 
 */
