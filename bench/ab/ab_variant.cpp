/* Library form: the batch entry points are defined once, in the library .cpp. Since the
 * refactored header also offers static inline definitions of the same public names by
 * default, the header has to be told to declare only -- FV_BUILD does exactly that (same
 * externally visible behaviour as FV_USE_EXTERN). Without it both definitions land in this
 * TU and the compiler rejects the redefinition. Harmless for an older header that predates
 * the flag. The inline form (AB_WITH_SRC=0) must not set it. */
#if defined(AB_WITH_SRC) && AB_WITH_SRC && !defined(FV_BUILD)
#define FV_BUILD 1
#endif

#include AB_HDR /* this variant public header */

#if defined(AB_WITH_SRC) && AB_WITH_SRC
#include AB_SRC /* library form: the batch entry point implementations */
#endif

