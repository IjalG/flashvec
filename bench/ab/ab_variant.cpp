#else
    /* Degradation: with o == a, _mask's "write a[i] back outside the mask" is bit-identical
     * to the in-place semantics. (Formally o overlapping a violates the __restrict contract,
     * but that kernel reads-modifies-writes 4 elements at a time with no cross-element
     * dependency and is bit-identical in practice; the gate catches any mismatch.) */
    fv_vec2_add_x4_mask((const fv_vec2 *)p->a, (const fv_vec2 *)p->b, (fv_vec2 *)p->a, p->mask,
                        n);
